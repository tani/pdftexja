#!/usr/bin/env python3
"""Build a metric-identical stand-in for the ipaex-type1 package.

usage: python3 tests/make-standin-ipaex-type1.py <texmf-tree>

The default fontset (ipaex-type1) needs the ipaex-type1 package: C70
font definitions for the families ipxm/ipxg (and ipxma/ipxga) and the
Unicode subfont TFMs ipxm-r-uXX / ipxg-r-uXX.  TeX Live distributions that
split TeX Live into packages (Debian/Ubuntu) do not ship it, so the gate
suites cannot run there.  This script derives an equivalent tree from the
IPAex TTFs that are installed (kpsewhich ipaexm.ttf / ipaexg.ttf):

  fonts/tfm/pdftexja-standin/   ipxm-r-uXX.tfm, ipxg-r-uXX.tfm
      ttf2tfm subfonts (Unicode.sfd) rewritten to the ipaex-type1 metric
      conventions: CHARWD = advance/unitsPerEm rounded half-up to 3
      decimals, CHARHT 0.88 / CHARDP 0.12 for every glyph, FONTDIMEN
      SPACE/STRETCH/SHRINK/EXTRASPACE 0, XHEIGHT 0.5, QUAD 1.0.  (Plain
      ttf2tfm output has a 0.29em interword space, which adds a glue at
      every CJK box head, and per-glyph heights.)
  fonts/truetype/pdftexja-standin/   copies of the TTFs whose PostScript
      name is IMFCTT1 / IGFCTT1 (the embedded name of ipaex-type1).
  tex/latex/pdftexja-standin/   c70ipxm.fd, c70ipxg.fd, c70ipxma.fd,
      c70ipxga.fd with a \\pdfmapline for the TTF subfonts.

Only metrics and names match: the glyphs are embedded as TrueType, not
Type 1.  Use the tree as TEXMFHOME (together with the staged pdftexja
tree) for tests/run-tests.sh and tests/run-class-tests.sh.  Never install
it next to a real ipaex-type1.
"""
import glob
import os
import re
import shutil
import subprocess
import sys
import tempfile

from fontTools.ttLib import TTFont

FONTDIMEN = """(FONTDIMEN
   (SLANT R 0.0)
   (SPACE R 0.0)
   (STRETCH R 0.0)
   (SHRINK R 0.0)
   (XHEIGHT R 0.5)
   (QUAD R 1.0)
   (EXTRASPACE R 0.0)
   )
"""

# family -> (TTF, subfont prefix, PostScript name, stand-in TTF name)
FACES = {
    "ipxm": ("ipaexm.ttf", "ipxm-r-u", "IMFCTT1", "pdftexja-standin-ipxm.ttf"),
    "ipxg": ("ipaexg.ttf", "ipxg-r-u", "IGFCTT1", "pdftexja-standin-ipxg.ttf"),
}

FD = """%% {name} -- pdftexja TEST stand-in for ipaex-type1 (generated by
%% tests/make-standin-ipaex-type1.py; metrics only, TrueType glyphs).
\\ProvidesFile{{{name}}}[pdftexja stand-in]
\\pdfmapline{{+{prefix}@Unicode@ <{ttf}}}
\\DeclareFontFamily{{C70}}{{{family}}}{{\\hyphenchar\\font\\m@ne}}
\\DeclareFontShape{{C70}}{{{family}}}{{m}}{{n}}{{<->CJK*{prefix}}}{{}}
\\DeclareFontShape{{C70}}{{{family}}}{{m}}{{sl}}{{<->CJKssub*{family}/m/n}}{{}}
\\DeclareFontShape{{C70}}{{{family}}}{{m}}{{it}}{{<->CJKssub*{family}/m/n}}{{}}
\\DeclareFontShape{{C70}}{{{family}}}{{m}}{{sc}}{{<->CJKssub*{family}/m/n}}{{}}
\\DeclareFontShape{{C70}}{{{family}}}{{bx}}{{n}}{{<->CJKssub*{family}/m/n}}{{}}
\\DeclareFontShape{{C70}}{{{family}}}{{bx}}{{sl}}{{<->CJKssub*{family}/m/n}}{{}}
\\DeclareFontShape{{C70}}{{{family}}}{{bx}}{{it}}{{<->CJKssub*{family}/m/n}}{{}}
\\DeclareFontShape{{C70}}{{{family}}}{{bx}}{{sc}}{{<->CJKssub*{family}/m/n}}{{}}
\\DeclareFontShape{{C70}}{{{family}}}{{b}}{{n}}{{<->CJKssub*{family}/m/n}}{{}}
\\DeclareFontShape{{C70}}{{{family}}}{{b}}{{sl}}{{<->CJKssub*{family}/m/n}}{{}}
\\DeclareFontShape{{C70}}{{{family}}}{{b}}{{it}}{{<->CJKssub*{family}/m/n}}{{}}
\\DeclareFontShape{{C70}}{{{family}}}{{b}}{{sc}}{{<->CJKssub*{family}/m/n}}{{}}
"""


def kpsewhich(name):
    path = subprocess.run(["kpsewhich", name], capture_output=True,
                          text=True).stdout.strip()
    if not path:
        sys.exit("make-standin-ipaex-type1: cannot find %s via kpsewhich" % name)
    return path


def rewrite_tfms(ttf, prefix, tfmdir):
    font = TTFont(ttf)
    upm = font["head"].unitsPerEm
    cmap = font.getBestCmap()
    hmtx = font["hmtx"].metrics
    count = 0
    for tfm in sorted(glob.glob(os.path.join(tfmdir, prefix + "[0-9a-f][0-9a-f].tfm"))):
        plane = int(os.path.basename(tfm)[len(prefix):len(prefix) + 2], 16)
        pl = subprocess.run(["tftopl", tfm], capture_output=True, text=True,
                            check=True).stdout
        head = pl.split("(CHARACTER", 1)[0]
        head = re.sub(r"\(FONTDIMEN\n(?:   .*\n)*   \)\n", FONTDIMEN, head)
        head = re.sub(r"\(LIGTABLE\n(?:   .*\n)*   \)\n", "", head)
        out = [head]
        for m in re.finditer(r"\(CHARACTER (O|C) (\S+)\n(?:   .*\n)*?   \)\n", pl):
            kind, val = m.groups()
            code = int(val, 8) if kind == "O" else ord(val)
            glyph = cmap.get(plane * 256 + code)
            if glyph is None:
                continue
            wd = int(hmtx[glyph][0] / upm * 1000 + 0.5) / 1000
            out.append("(CHARACTER %s %s\n   (CHARWD R %r)\n   (CHARHT R 0.88)\n"
                       "   (CHARDP R 0.12)\n   )\n" % (kind, val, float(wd)))
        plfile = tfm[:-4] + ".pl"
        with open(plfile, "w") as fh:
            fh.write("".join(out))
        subprocess.run(["pltotf", plfile, tfm], check=True, capture_output=True)
        os.remove(plfile)
        count += 1
    return count


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__.split("\n\n", 2)[1])
    tree = os.path.abspath(sys.argv[1])
    tfmdir = os.path.join(tree, "fonts", "tfm", "pdftexja-standin")
    ttfdir = os.path.join(tree, "fonts", "truetype", "pdftexja-standin")
    fddir = os.path.join(tree, "tex", "latex", "pdftexja-standin")
    for d in (tfmdir, ttfdir, fddir):
        shutil.rmtree(d, ignore_errors=True)
        os.makedirs(d)
    for family, (ttfname, prefix, psname, standin) in FACES.items():
        ttf = kpsewhich(ttfname)
        # ttf2tfm writes the subfont TFMs into the current directory
        with tempfile.TemporaryDirectory() as tmp:
            subprocess.run(["ttf2tfm", ttf, "-q", prefix + "@Unicode@"], cwd=tmp,
                           check=True, capture_output=True)
            for tfm in glob.glob(os.path.join(tmp, prefix + "*.tfm")):
                shutil.move(tfm, tfmdir)
        n = rewrite_tfms(ttf, prefix, tfmdir)
        font = TTFont(ttf)
        for rec in font["name"].names:
            if rec.nameID == 6:
                rec.string = psname
        font.save(os.path.join(ttfdir, standin))
        for fam in (family, family + "a"):
            name = "c70%s.fd" % fam
            with open(os.path.join(fddir, name), "w") as fh:
                fh.write(FD.format(name=name, prefix=prefix, ttf=standin, family=fam))
        print("make-standin-ipaex-type1: %s: %d TFM(s), %s as %s"
              % (family, n, ttfname, psname))


if __name__ == "__main__":
    main()
